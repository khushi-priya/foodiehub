const express = require('express');
const router = express.Router();
const { requireCustomer } = require('./customer.middleware');
const controller = require('./customer.controller');
const checkout = require('./checkout.controller');
const reservations = require('./reservation.controller');
const support = require('../support/customer.controller');
const notifications = require('./notification.controller');

router.use(requireCustomer);
router.get('/summary', controller.summary);
router.get('/support/options', support.options);
router.get('/support/tickets', support.list);
router.post('/support/tickets', support.create);
router.get('/support/tickets/:ticketId', support.details);
router.post('/support/tickets/:ticketId/replies', support.reply);
router.get('/support/attachments/:attachmentId', support.downloadAttachment);
router.get('/notifications', notifications.list);
router.patch('/notifications/:notificationId/read', notifications.markRead);
router.post('/notifications/read-all', notifications.markAllRead);
router.get('/notification-preferences', notifications.preferences);
router.patch('/notification-preferences', notifications.updatePreferences);
router.get('/reservations', reservations.listMine);
router.post('/reservations', reservations.create);
router.patch('/reservations/:reservationId/cancel', reservations.cancelMine);
router.get('/profile', controller.profile);
router.get('/geocoding/search', controller.searchMapAddress);
router.get('/geocoding/reverse', controller.reverseMapAddress);
router.put('/profile', controller.updateProfile);
router.put('/password', controller.changePassword);
router.get('/orders', controller.orders);
router.get('/orders/:orderId', checkout.getOrder);
router.post('/orders', checkout.placeOrder);
router.patch('/orders/:orderId/cancel', checkout.cancelOrder);
router.post('/orders/:orderId/reorder', checkout.reorder);
router.get('/cart', checkout.getCart);
router.post('/cart/items', checkout.addItem);
router.patch('/cart/items/:itemId', checkout.updateItem);
router.delete('/cart/items/:itemId', checkout.removeItem);
router.delete('/cart', checkout.clearCart);
router.get('/checkout/summary', checkout.checkoutSummary);
router.post('/checkout/idempotency-key', checkout.createIdempotencyKey);
router.post('/checkout/validate', checkout.validateCheckout);
router.post('/checkout/razorpay/order', checkout.createRazorpayOrder);
router.post('/orders/:orderId/payments/razorpay/verify', checkout.verifyRazorpayPayment);
router.post('/orders/:orderId/payments/razorpay/failure', checkout.recordRazorpayFailure);
router.post('/orders/:orderId/payments/razorpay/cancel', checkout.recordRazorpayCancellation);
router.get('/addresses', controller.addresses);
router.post('/addresses', controller.createAddress);
router.put('/addresses/:addressId', controller.updateAddress);
router.delete('/addresses/:addressId', controller.deleteAddress);
router.get('/wishlist', controller.wishlist);
router.post('/wishlist', controller.addWishlist);
router.delete('/wishlist/:wishlistItemId', controller.removeWishlist);

module.exports = router;
